"""Disconnect-proof progress journal.

Two stores, both under ``artifacts/progress`` (Google Drive on Colab):

* ``state.json``   - latest known state, rewritten atomically after every stage.
* ``runs.jsonl``   - append-only event log (never rewritten, never truncated).

Plus a human-readable ``progress.md`` in the repo root AND in artifacts. Only the
block between the ``BEGIN:AUTO`` / ``END:AUTO`` markers is machine-written, so
your own notes in that file survive every update.

Everything here is pure-python + stdlib so it works before any ML dependency is
installed (e.g. right after a Colab disconnect).
"""

from __future__ import annotations

import json
import os
import platform
import time
from pathlib import Path
from typing import Any

from .paths import Paths

BEGIN = "<!-- BEGIN:AUTO (generated by sheng_voxcpm.progress, do not edit) -->"
END = "<!-- END:AUTO -->"

# Stage -> (human label, what to run next when this stage is the latest one)
STAGES: dict[str, tuple[str, str]] = {
    "setup": ("Environment + VoxCPM repo installed", "sheng-voxcpm env"),
    "data": ("Dataset downloaded, 16 kHz WAVs + manifests built", "sheng-voxcpm data"),
    "model": ("openbmb/VoxCPM2 snapshot downloaded", "sheng-voxcpm model"),
    "train": ("LoRA fine-tuning", "sheng-voxcpm train"),
    "eval": ("Checkpoint evaluation / A-B listening", "sheng-voxcpm eval"),
    "export": ("Package final LoRA + samples", "sheng-voxcpm status"),
}

MD_HEADER = """# Progress - VoxCPM2 x Sheng LoRA

Sheng = Kenyan Swahili + English code-switching. Base model: `openbmb/VoxCPM2`
(2B, tokenizer-free diffusion-AR TTS). Dataset: `lyle-mlengineer/kenyan-celebs`
(42 clips x 30 s, single speaker "abel").

**After a Colab disconnect, run this first:**

```bash
python -m sheng_voxcpm.cli status          # what is already done, where the checkpoints are
python -m sheng_voxcpm.cli train --resume  # continues from <checkpoints>/latest automatically
```

"""

MD_NOTES = """
## Notes / decisions (hand-written, preserved)

- LoRA (not full fine-tune): 42 clips / ~21 min is far below the ~500 h the
  official docs want for adding a new language, and full FT would forget more.
- `sample_rate: 16000` is mandatory (AudioVAE encoder input). Setting 48000
  silently trains on 3x-too-long latents and outputs garbage (upstream
  issue #202). `out_sample_rate: 48000` only affects TensorBoard audio logs.
- `enable_dit: true`, `enable_proj: false`, `r=32` = the docs' single-speaker
  starting point. `r=64` variant is provided for a style/language push.
- `save_path` lives on Google Drive so `<save_path>/latest` survives a
  disconnect; `train_voxcpm_finetune.py` auto-resumes from it.
- No `ref_audio` in the manifests by default (single speaker + only 38 training
  clips; reference conditioning roughly doubles sequence length). Enable with
  `--ref-audio-fraction 0.35` if you later add more speakers/data.
"""


def _now() -> str:
    return time.strftime("%Y-%m-%d %H:%M:%S")


def _atomic_write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with tmp.open("w", encoding="utf-8", newline="\n") as f:
        f.write(text)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)


class Progress:
    """Read/write the durable progress state."""

    def __init__(self, paths: Paths):
        self.paths = paths
        paths.progress_dir.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------ state
    def load(self) -> dict[str, Any]:
        try:
            with self.paths.state_json.open("r", encoding="utf-8") as f:
                data = json.load(f)
        except (FileNotFoundError, json.JSONDecodeError):
            data = {}
        data.setdefault("stages", {})
        data.setdefault("created", _now())
        return data

    def save(self, state: dict[str, Any]) -> None:
        state["updated"] = _now()
        state["host"] = {
            "platform": platform.platform(),
            "python": platform.python_version(),
        }
        _atomic_write_text(self.paths.state_json, json.dumps(state, indent=2, ensure_ascii=False))

    def set_state(self, **kwargs: Any) -> dict[str, Any]:
        state = self.load()
        state.update(kwargs)
        self.save(state)
        return state

    # ----------------------------------------------------------- events
    def event(self, stage: str, status: str = "done", note: str = "", **extra: Any) -> None:
        """Record a stage transition and refresh progress.md."""
        if stage not in STAGES:
            raise KeyError(f"unknown stage {stage!r}; known: {sorted(STAGES)}")
        state = self.load()
        state["stages"][stage] = {
            "status": status,
            "note": note,
            "at": _now(),
            **extra,
        }
        if status == "running":
            state["current_stage"] = stage
        elif state.get("current_stage") == stage:
            state["current_stage"] = None
        self.save(state)

        evt = {"ts": _now(), "stage": stage, "status": status, "note": note, **extra}
        self.paths.runs_jsonl.parent.mkdir(parents=True, exist_ok=True)
        with self.paths.runs_jsonl.open("a", encoding="utf-8") as f:
            f.write(json.dumps(evt, ensure_ascii=False) + "\n")

        self.write_markdown(state)

    def is_done(self, stage: str) -> bool:
        return self.load()["stages"].get(stage, {}).get("status") == "done"

    # -------------------------------------------------------- rendering
    def _next_step(self, state: dict[str, Any]) -> str:
        stages = state["stages"]
        for stage, (label, cmd) in STAGES.items():
            if stage == "train" and stages.get(stage, {}).get("status") == "running":
                return f"`{cmd} --resume`   # training was interrupted - resume it"
            if stage == "train" and stages.get(stage, {}).get("status") == "partial":
                return f"`{cmd} --resume`   # partial results, continue"
            if stages.get(stage, {}).get("status") != "done":
                return f"`{cmd}`   # {label}"
        return "All stages done - run `sheng-voxcpm status` to inspect artifacts, `sheng-voxcpm export` to package."

    def render_markdown(self, state: dict[str, Any] | None = None) -> str:
        state = state or self.load()
        stages = state["stages"]
        lines = [BEGIN, "", f"_Last update: {state.get('updated', 'never')}  |  " f"{state.get('run', 'run not set')}_", ""]
        lines += ["| # | Stage | What it means | Status | When | Detail |", "|---|---|---|---|---|---|"]
        for i, (stage, (label, _cmd)) in enumerate(STAGES.items(), start=1):
            info = stages.get(stage, {})
            status = info.get("status", "todo")
            icon = {"done": "done", "running": "RUNNING", "partial": "partial", "failed": "FAILED"}.get(status, "todo")
            detail = str(info.get("note") or "").replace("|", "/").replace("\n", " ")
            lines.append(f"| {i} | `{stage}` | {label} | **{icon}** | {info.get('at', '-')} | {detail} |")
        lines.append("")

        ckpt = state.get("checkpoint") or {}
        if ckpt:
            lines += [
                "### Last checkpoint",
                "",
                f"- step: `{ckpt.get('step')}`",
                f"- path: `{ckpt.get('path', '-')}`",
                f"- loss/diff: `{ckpt.get('loss_diff', '-')}`  loss/stop: `{ckpt.get('loss_stop', '-')}`",
                "",
            ]
        if state.get("best_checkpoint"):
            lines += [f"**Best checkpoint (by eval):** `{state['best_checkpoint']}`", ""]

        lines += ["### Next command", "", f"> {self._next_step(state)}", ""]
        if state.get("notes"):
            lines += ["### Machine notes", ""]
            lines += [f"- {n}" for n in state["notes"]]

        lines += [
            "",
            "### Locations",
            "",
            f"- artifacts root: `{self.paths.artifacts}`",
            f"- VoxCPM repo: `{self.paths.voxcpm_repo}`",
            f"- base model: `{self.paths.model_dir}`",
            f"- manifests: `{self.paths.manifest_dir}`",
            f"- checkpoints: `{self.paths.checkpoint_root}`",
            f"- train log: `{self.paths.train_log(state.get('run', 'lora_r32'))}`",
            f"- evals: `{self.paths.eval_root}`",
            "",
            END,
        ]
        return "\n".join(lines)

    def add_note(self, note: str) -> None:
        state = self.load()
        notes = state.setdefault("notes", [])
        notes.append(f"{_now()}: {note}")
        self.save(state)
        self.write_markdown(state)

    def write_markdown(self, state: dict[str, Any] | None = None) -> list[Path]:
        """Merge the AUTO block into every progress.md (artifacts + repo)."""
        block = self.render_markdown(state)
        written: list[Path] = []
        seen: set[Path] = set()
        for path in (self.paths.repo_progress_md, self.paths.artifacts_progress_md):
            path = path.resolve()
            if path in seen:
                continue
            seen.add(path)
            try:
                existing = path.read_text(encoding="utf-8") if path.exists() else self._default_md()
            except OSError:
                existing = self._default_md()
            updated = _replace_block(existing, block)
            _atomic_write_text(path, updated)
            written.append(path)
        return written

    def _default_md(self) -> str:
        return MD_HEADER + BEGIN + "\n" + END + "\n" + MD_NOTES

    # -------------------------------------------------------------- misc
    def tail_events(self, n: int = 15) -> list[dict[str, Any]]:
        try:
            lines = self.paths.runs_jsonl.read_text(encoding="utf-8").splitlines()
        except FileNotFoundError:
            return []
        out = []
        for line in lines[-n:]:
            try:
                out.append(json.loads(line))
            except json.JSONDecodeError:
                continue
        return out


def _replace_block(text: str, block: str) -> str:
    if BEGIN in text and END in text:
        head, _, rest = text.partition(BEGIN)
        _, _, tail = rest.partition(END)
        return head + block + tail
    if not text.strip():
        return MD_HEADER + block + MD_NOTES
    return text.rstrip() + "\n\n" + block + "\n" + MD_NOTES


def seed_progress_md(paths: Paths) -> Path:
    """Create progress.md from the template if it does not exist yet."""
    p = Progress(paths)
    if not paths.repo_progress_md.exists():
        _atomic_write_text(paths.repo_progress_md, p._default_md())
    p.write_markdown()
    return paths.repo_progress_md
