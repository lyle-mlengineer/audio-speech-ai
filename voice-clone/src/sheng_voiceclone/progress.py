"""Disconnect-proof progress journal.

Two machine stores under ``<artifacts>/progress``:

* ``state.json`` - latest known state, rewritten atomically after every update;
* ``runs.jsonl`` - append-only event log (never rewritten).

Plus a human-readable ``progress.md`` written to **the repo root and the
artifacts root**, so it survives both a lost VM and a fresh clone. Only the block
between the ``BEGIN:AUTO`` / ``END:AUTO`` markers is machine-written; hand notes
outside it survive every update.

Pure stdlib: this must run on a fresh Colab VM right after a disconnect, before
any ML dependency is installed.
"""

from __future__ import annotations

import json
import os
import time
from pathlib import Path
from typing import Any

from .paths import REPO_ROOT, Paths, is_inside, on_drive

BEGIN = "<!-- BEGIN:AUTO (generated by sheng_voiceclone.progress, do not edit) -->"
END = "<!-- END:AUTO -->"

# stage -> (human label, command that advances it)
STAGES: dict[str, tuple[str, str]] = {
    "setup": ("Environment (torch + chatterbox-tts) ready", "sheng-voiceclone setup"),
    "data": ("Dataset -> 16 kHz WAVs, splits, reference clip", "sheng-voiceclone data"),
    "model": ("ResembleAI/chatterbox snapshot downloaded", "sheng-voiceclone model"),
    "baseline": ("Zero-shot clone synthesised + scored (the number to beat)", "sheng-voiceclone baseline"),
    "train": ("T3 fine-tune (Sheng voice)", "sheng-voiceclone train"),
    "eval": ("Fine-tuned checkpoint synthesised + scored", "sheng-voiceclone eval"),
    "compare": ("Baseline vs tuned verdict", "sheng-voiceclone compare"),
}

ORDER = list(STAGES)


def _now() -> str:
    return time.strftime("%Y-%m-%d %H:%M:%S")


def load_state(paths: Paths) -> dict[str, Any]:
    if paths.state_file.is_file():
        try:
            return json.loads(paths.state_file.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            pass
    return {"stages": {}, "run": None, "updated": None}


def _save_state(paths: Paths, state: dict[str, Any]) -> None:
    paths.progress_dir.mkdir(parents=True, exist_ok=True)
    tmp = paths.state_file.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(state, indent=2), encoding="utf-8")
    os.replace(tmp, paths.state_file)


def record(
    paths: Paths,
    stage: str,
    status: str,
    *,
    detail: str = "",
    run: str | None = None,
) -> dict[str, Any]:
    """Mark a stage ``done`` / ``running`` / ``failed`` and rewrite the journal."""
    if stage not in STAGES:
        raise KeyError(f"unknown stage '{stage}' (have: {', '.join(STAGES)})")
    state = load_state(paths)
    state.setdefault("stages", {})[stage] = {"status": status, "when": _now(), "detail": detail}
    if run:
        state["run"] = run
    state["updated"] = _now()
    _save_state(paths, state)

    paths.progress_dir.mkdir(parents=True, exist_ok=True)
    with paths.events_file.open("a", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps({"ts": _now(), "stage": stage, "status": status, "detail": detail}) + "\n")
    write_md(paths, state)
    return state


def status_of(paths: Paths, stage: str) -> str:
    return str(load_state(paths).get("stages", {}).get(stage, {}).get("status", "todo"))


def next_stage(paths: Paths) -> str | None:
    for s in ORDER:
        if status_of(paths, s) != "done":
            return s
    return None


def summary(paths: Paths) -> str:
    """One screen: every stage, its state, and the next command to run."""
    state = load_state(paths)
    lines = [f"artifacts: {paths.root}", f"run: {state.get('run') or '-'}", ""]
    for s in ORDER:
        info = state.get("stages", {}).get(s, {})
        st = info.get("status", "todo")
        mark = {"done": "ok  ", "running": "RUN ", "failed": "FAIL"}.get(st, "todo")
        lines.append(f"  [{mark}] {s:<8} {STAGES[s][0]}")
        if info.get("detail"):
            lines.append(f"            {info['detail']}")
    nxt = next_stage(paths)
    lines.append("")
    if nxt:
        lines.append(f"next: {STAGES[nxt][1]}")
    else:
        lines.append("next: nothing - all stages done. Listen, then publish.")
    return "\n".join(lines)


def render_md(paths: Paths, state: dict[str, Any]) -> str:
    stages = state.get("stages", {})
    rows = [
        f"_Last update: {state.get('updated') or '-'}  |  run: {state.get('run') or '-'}_",
        "",
        "| # | Stage | What it means | Status | When | Detail |",
        "|---|---|---|---|---|---|",
    ]
    for i, s in enumerate(ORDER, start=1):
        info = stages.get(s, {})
        st = info.get("status", "todo")
        shown = f"**{st}**" if st == "done" else st
        rows.append(
            f"| {i} | `{s}` | {STAGES[s][0]} | {shown} | {info.get('when') or '-'} | "
            f"{(info.get('detail') or '').replace('|', '/')} |"
        )
    nxt = next_stage(paths)
    rows += ["", "### Next command", ""]
    rows.append(f"> `{STAGES[nxt][1]}`" if nxt else "> all stages done")
    rows += [
        "",
        "### Locations",
        "",
        f"- artifacts root: `{paths.root}`",
        f"- manifests: `{paths.manifests}`",
        f"- reference clip: `{paths.ref_audio}`",
        f"- checkpoints: `{paths.checkpoints}`",
        f"- evals: `{paths.evals}`",
        f"- scores: `{paths.scores}`",
    ]
    return "\n".join(rows)


def _mirror_targets(paths: Paths) -> list[Path]:
    """progress.md in the artifacts root, plus the repo copy when it is meaningful.

    The repo copy exists so a fresh clone shows the state without the VM. It only
    makes sense when artifacts are this checkout's own ``./artifacts`` or a Drive
    mount - never when they are a throwaway temp dir (tests, demos).
    """
    targets = [paths.root / "progress.md"]
    if is_inside(paths.root, REPO_ROOT) or on_drive(paths.root):
        targets.append(REPO_ROOT / "progress.md")
    return targets


def write_md(paths: Paths, state: dict[str, Any]) -> list[Path]:
    """Replace the AUTO block in progress.md (artifacts root, and the repo)."""
    block = f"{BEGIN}\n{render_md(paths, state)}\n{END}"
    written: list[Path] = []
    for target in _mirror_targets(paths):
        if target.parent != paths.root and not target.parent.is_dir():
            continue
        try:
            existing = target.read_text(encoding="utf-8") if target.is_file() else ""
        except OSError:
            continue
        if BEGIN in existing and END in existing:
            head, rest = existing.split(BEGIN, 1)
            _, tail = rest.split(END, 1)
            new = f"{head}{block}{tail}"
        elif existing.strip():
            new = existing.rstrip() + "\n\n" + block + "\n"
        else:
            new = "# Progress\n\n" + block + "\n"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(new, encoding="utf-8", newline="\n")
        written.append(target)
    return written
