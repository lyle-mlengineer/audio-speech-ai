"""Stage tracking that survives a Colab disconnect.

State lives in ``<artifacts>/progress/state.json`` so it is on Drive with the
checkpoints, and a human-readable copy is mirrored into ``progress.md`` (repo
root, between AUTO markers) so the next session can see what is left without
opening the notebook.
"""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path

from .paths import Paths

STAGES: list[tuple[str, str]] = [
    ("setup", "Environment (torch + qwen-tts) ready"),
    ("data", "Dataset -> 24 kHz WAVs + manifests"),
    ("model", "Base model + 12 Hz tokenizer snapshots"),
    ("codes", "audio_codes extracted (prepare_data.py step)"),
    ("train", "SFT on Sheng"),
    ("eval", "Checkpoint synthesised + sanity checked"),
    ("export", "Model dir + samples packaged"),
]

BEGIN = "<!-- BEGIN:AUTO (generated by sheng_qwentts.progress, do not edit) -->"
END = "<!-- END:AUTO -->"

DONE, RUNNING, FAILED, TODO = "done", "running", "failed", "todo"


def _now() -> str:
    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")


class Progress:
    def __init__(self, paths: Paths, run: str):
        self.paths = paths
        self.run = run
        self.state = self._load()

    # ------------------------------------------------------------------ io
    def _load(self) -> dict:
        path = self.paths.state_json
        if path.is_file():
            try:
                state = json.loads(path.read_text(encoding="utf-8"))
            except json.JSONDecodeError:
                state = {}
        else:
            state = {}
        state.setdefault("stages", {})
        state["run"] = self.run
        return state

    def save(self) -> None:
        self.paths.progress_dir.mkdir(parents=True, exist_ok=True)
        self.state["updated"] = _now()
        self.paths.state_json.write_text(
            json.dumps(self.state, indent=2) + "\n", encoding="utf-8", newline="\n"
        )
        markdown = self.render_markdown()
        self.paths.artifacts_progress_md.write_text(markdown, encoding="utf-8", newline="\n")
        self._mirror_into_repo(markdown)

    def _mirror_into_repo(self, markdown: str) -> None:
        repo_md = self.paths.repo_progress_md
        if repo_md.is_file():
            text = repo_md.read_text(encoding="utf-8")
            if BEGIN in text and END in text:
                head, rest = text.split(BEGIN, 1)
                _, tail = rest.split(END, 1)
                repo_md.write_text(head + BEGIN + "\n" + markdown + END + tail,
                                   encoding="utf-8", newline="\n")
                return
        repo_md.write_text(markdown, encoding="utf-8", newline="\n")

    # --------------------------------------------------------------- write
    def mark(self, stage: str, status: str, detail: str = "") -> None:
        if stage not in dict(STAGES):
            raise ValueError(f"unknown stage {stage!r}; known: {[s for s, _ in STAGES]}")
        entry = self.state["stages"].setdefault(stage, {})
        if status == RUNNING:
            entry["started"] = _now()
        entry["status"] = status
        entry["when"] = _now()
        if detail:
            entry["detail"] = detail
        self.save()

    def note(self, key: str, value) -> None:
        self.state[key] = value
        self.save()

    def get(self, stage: str, key: str, default=None):
        return self.state["stages"].get(stage, {}).get(key, default)

    def status(self, stage: str) -> str:
        return self.get(stage, "status", TODO)

    def is_done(self, stage: str) -> bool:
        return self.status(stage) == DONE

    # -------------------------------------------------------------- render
    def render_markdown(self) -> str:
        icon = {DONE: "**done**", RUNNING: "**running**", FAILED: "**FAILED**", TODO: "todo"}
        lines = [
            "",
            f"_Last update: {self.state.get('updated', _now())}  |  run: {self.run}_",
            "",
            "| # | Stage | What it means | Status | When | Detail |",
            "|---|---|---|---|---|---|",
        ]
        for i, (stage, meaning) in enumerate(STAGES, start=1):
            entry = self.state["stages"].get(stage, {})
            status = icon.get(entry.get("status", TODO), "todo")
            detail = str(entry.get("detail", "")).replace("|", "/").strip()
            lines.append(
                f"| {i} | `{stage}` | {meaning} | {status} | {entry.get('when', '-')} | {detail} |"
            )
        lines.append("")
        return "\n".join(lines)

    def render_console(self) -> str:
        width = max(len(s) for s, _ in STAGES)
        out = [f"run: {self.run}   artifacts: {self.paths.artifacts}"]
        for stage, meaning in STAGES:
            entry = self.state["stages"].get(stage, {})
            status = entry.get("status", TODO)
            detail = entry.get("detail", "")
            out.append(f"  {stage.ljust(width)}  {status.ljust(7)}  {detail}  # {meaning}")
        return "\n".join(out)
