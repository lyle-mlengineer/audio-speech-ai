"""Render the reference YAML templates in ``configs/`` from ``config.py``.

The CLI renders its own YAML into ``<artifacts>/configs/<run>.yaml`` at train
time; the files here exist so a human can read what will be written without a
GPU or an artifacts root. ``tests/test_config_templates.py`` keeps them in sync.

    python scripts/render_configs.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from kenya_voices.config import DEFAULT_STEPS, PROFILES, TrainConfig, render_yaml  # noqa: E402
from kenya_voices.paths import Paths  # noqa: E402


def main() -> int:
    out_dir = ROOT / "configs"
    out_dir.mkdir(parents=True, exist_ok=True)
    # Placeholders so the templates are readable without an artifacts root.
    fake = Paths(artifacts=Path("/content/drive/MyDrive/kenya-voices"), code_root=ROOT)
    posix_root = "/content/drive/MyDrive/kenya-voices"
    for profile in sorted(PROFILES):
        cfg = TrainConfig(profile=profile, steps=DEFAULT_STEPS)
        payload = {
            key: (value.replace(str(fake.artifacts), posix_root).replace("\\", "/") if isinstance(value, str) and value else value)
            for key, value in cfg.build_payload(fake).items()
        }
        header = (
            f"# reference template - generated by scripts/render_configs.py\n"
            f"# profile={profile}: {PROFILES[profile]['note']}\n"
            f"# the real config is rendered per run into <artifacts>/configs/<run>.yaml\n"
        )
        path = out_dir / f"voxcpm2_design_lora_{profile}.yaml"
        path.write_text(header + render_yaml(payload) + "\n", encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
