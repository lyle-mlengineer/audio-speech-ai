"""The rendered YAML must be exactly what VoxCPM2's trainer asserts on."""

from __future__ import annotations

import json

import pytest

from kenya_voices.config import DEFAULT_STEPS, LORA_R, PROFILES, TrainConfig, render_yaml, write_config


def _parse(text: str) -> dict:
    """Tiny reader for the subset ``render_yaml`` emits (no PyYAML dependency)."""
    out: dict = {}
    stack = [(-1, out)]
    for raw in text.splitlines():
        line = raw.split(" #")[0].rstrip() if raw.lstrip().startswith("#") else raw.rstrip()
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        indent = len(line) - len(line.lstrip())
        key, _, value = line.strip().partition(":")
        while stack and indent <= stack[-1][0]:
            stack.pop()
        parent = stack[-1][1]
        value = value.strip()
        if value == "":
            parent[key] = {}
            stack.append((indent, parent[key]))
            continue
        if value in ("true", "false"):
            parent[key] = value == "true"
        elif value in ("null", "~"):
            parent[key] = None
        elif value.startswith('"'):
            parent[key] = json.loads(value)
        else:
            try:
                parent[key] = int(value)
            except ValueError:
                parent[key] = float(value)
    return out


def test_sample_rates(tmp_path):
    cfg = TrainConfig()
    payload = cfg.build_payload(_paths(tmp_path))
    assert payload["sample_rate"] == 16_000
    assert payload["out_sample_rate"] == 48_000


def _paths(tmp_path):
    from kenya_voices.paths import Paths

    paths = Paths(artifacts=tmp_path / "artifacts", code_root=tmp_path)
    paths.ensure()
    return paths


def test_steps_mean_one_thing():
    payload = TrainConfig(steps=900).resolved()
    assert payload["num_iters"] == payload["max_steps"] == 900
    assert DEFAULT_STEPS >= 600


def test_lora_block():
    payload = TrainConfig(lora_r=16, lora_alpha=None).resolved()
    lora = payload["lora"]
    assert lora["r"] == 16
    assert lora["alpha"] == 16  # None -> same as r
    assert lora["enable_lm"] and lora["enable_dit"]
    assert not lora["enable_proj"]  # keeps the adapter small and cheap on Colab
    assert LORA_R == 32


@pytest.mark.parametrize("profile", sorted(PROFILES))
def test_effective_batch_is_16(profile):
    payload = TrainConfig(profile=profile).resolved()
    assert payload["batch_size"] * payload["grad_accum_steps"] == 16


def test_paths_point_into_artifacts(tmp_path):
    paths = _paths(tmp_path)
    payload = TrainConfig().build_payload(paths)
    assert payload["pretrained_path"] == str(paths.model_dir)
    assert payload["train_manifest"] == str(paths.train_manifest)
    assert payload["save_path"] == str(paths.checkpoint_dir("design_r32"))
    assert payload["tensorboard"] == str(paths.tensorboard_dir("design_r32"))
    assert payload["distribute"] is False  # self-describing checkpoints on Drive


def test_missing_val_manifest_renders_empty(tmp_path):
    paths = _paths(tmp_path)
    assert TrainConfig().build_payload(paths)["val_manifest"] == ""
    paths.val_manifest.write_text("", encoding="utf-8")
    assert TrainConfig().build_payload(paths)["val_manifest"] == str(paths.val_manifest)


def test_overrides_win():
    cfg = TrainConfig(steps=100, overrides={"max_batch_tokens": 4096, "lora": {"r": 8}})
    payload = cfg.resolved()
    assert payload["max_batch_tokens"] == 4096
    assert payload["lora"]["r"] == 8


def test_yaml_scalars_are_typed():
    data = _parse(render_yaml({"a": 1, "b": 1e-4, "c": True, "d": None, "e": "x: y", "f": {"g": 0.5}}))
    assert data["a"] == 1 and isinstance(data["a"], int)
    assert data["b"] == pytest.approx(0.0001)
    assert data["e"] == "x: y" and data["f"]["g"] == pytest.approx(0.5)
    assert data["c"] is True
    assert data["d"] is None


def test_yaml_float_never_uses_exponent():
    text = render_yaml({"lr": 1e-5})
    assert "e-05" not in text.split(":")[1]
    assert _parse(text)["lr"] == pytest.approx(1e-5)


def test_write_config_has_header(tmp_path):
    paths = _paths(tmp_path)
    out = write_config(paths, TrainConfig(run="x"))
    text = out.read_text(encoding="utf-8")
    assert text.startswith("# generated by kenya_voices")
    assert out.name == "x.yaml"
    assert _parse(text)["sample_rate"] == 16_000
