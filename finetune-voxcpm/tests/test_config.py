"""Rendered training YAML: the values VoxCPM's trainer actually asserts on."""

from __future__ import annotations

import json

import pytest

from sheng_voxcpm.config import DEFAULT_STEPS, PROFILES, TrainConfig, profile_summary, render_yaml, write_config
from sheng_voxcpm.paths import Paths


@pytest.fixture()
def render(paths, mini_yaml):
    """Rendered training config, parsed back from the YAML text we emit."""

    def _render(**kwargs) -> dict:
        text = render_yaml(TrainConfig(**kwargs).build_payload(paths))
        return mini_yaml(text)

    return _render


def test_audio_vae_sample_rate_is_16k(render):
    """sample_rate is asserted against audio_vae.sample_rate upstream; 48k only logs."""
    for profile in PROFILES:
        cfg = render(profile=profile)
        assert cfg["sample_rate"] == 16_000
        assert cfg["out_sample_rate"] == 48_000


def test_paths_point_into_artifacts(paths, render):
    paths.val_manifest.write_text("", encoding="utf-8")  # present => referenced by the config
    cfg = render()
    assert cfg["pretrained_path"] == str(paths.model_dir)
    assert cfg["train_manifest"] == str(paths.train_manifest)
    assert cfg["val_manifest"] == str(paths.val_manifest)
    assert cfg["save_path"] == str(paths.checkpoint_dir("lora_r32"))
    assert cfg["tensorboard"] == str(paths.tensorboard_dir("lora_r32"))


def test_missing_val_manifest_renders_empty(paths, render):
    """A dataset too small to hold clips out yields no validation split."""
    assert not paths.val_manifest.exists()
    assert render()["val_manifest"] == ""


def test_num_iters_and_max_steps_agree(render):
    """num_iters bounds the loop, max_steps sizes the cosine schedule: keep them equal."""
    cfg = render(steps=123)
    assert cfg["num_iters"] == cfg["max_steps"] == 123
    assert cfg["warmup_steps"] < cfg["max_steps"]


def test_lora_block(render):
    cfg = render(lora_r=64, lora_alpha=None)
    lora = cfg["lora"]
    assert lora["enable_lm"] is True and lora["enable_dit"] is True
    assert lora["enable_proj"] is False
    assert lora["r"] == 64 and lora["alpha"] == 64  # alpha defaults to r
    assert lora["dropout"] == 0.0
    assert cfg["distribute"] is False  # checkpoints stay self-describing locally


def test_effective_batch_matches_official_shape(render):
    for profile, expected in (("l4", 16), ("a100", 16), ("t4", 16)):
        cfg = render(profile=profile)
        assert cfg["batch_size"] * cfg["grad_accum_steps"] == expected
        assert cfg["max_batch_tokens"] > 0


def test_overrides_win(render):
    cfg = render(overrides={"learning_rate": 5e-5, "max_grad_norm": 0.5})
    assert cfg["learning_rate"] == 5e-5
    assert cfg["max_grad_norm"] == 0.5


def test_yaml_scalars_are_typed():
    text = render_yaml({"a": True, "b": False, "c": None, "d": 1e-4, "e": "x y", "f": {"g": 2}})
    assert "a: true" in text and "b: false" in text
    assert "c: null" in text
    assert 'e: "x y"' in text
    assert "f:\n  g: 2" in text


def test_write_config_has_header(paths):
    out = write_config(paths, TrainConfig(steps=42))
    text = out.read_text(encoding="utf-8")
    assert text.startswith("# generated by sheng_voxcpm")
    assert out == paths.run_config("lora_r32")


def test_profile_summary_mentions_knobs(paths):
    summary = profile_summary(TrainConfig(profile="a100", steps=300))
    assert "profile=a100" in summary and "steps=300" in summary


@pytest.mark.parametrize("profile", sorted(PROFILES))
def test_template_matches_renderer(paths, mini_yaml, render, profile):
    """configs/voxcpm2_sheng_lora_<profile>.yaml documents what config.py renders."""
    template_path = paths.template_path(profile)
    assert template_path.exists(), f"missing template {template_path}"
    raw = template_path.read_text(encoding="utf-8").replace("${ARTIFACTS}", str(paths.artifacts))
    template = mini_yaml(raw)
    rendered = render(profile=profile)

    for key in (
        "sample_rate",
        "out_sample_rate",
        "batch_size",
        "grad_accum_steps",
        "max_batch_tokens",
        "num_workers",
        "preprocessing_num_workers",
        "learning_rate",
        "weight_decay",
        "warmup_steps",
        "max_grad_norm",
        "max_steps",
        "num_iters",
        "save_interval",
        "valid_interval",
        "log_interval",
        "distribute",
    ):
        assert template[key] == rendered[key], f"{profile}: {key} {template[key]!r} != {rendered[key]!r}"

    assert template["lora"] == rendered["lora"]
    assert template["lambdas"] == rendered["lambdas"]
    assert template["num_iters"] == template["max_steps"] == rendered["num_iters"]
    # Steps in the template are the documented default, not a hard-coded per-profile value.
    assert template["num_iters"] == DEFAULT_STEPS


def test_json_roundtrip_of_rendered_yaml(paths):
    """The YAML we emit must contain no non-JSON nonsense (tab/NaN/odd escapes)."""
    text = render_yaml(TrainConfig().build_payload(paths))
    assert "\t" not in text
    assert "nan" not in text.lower()
    json.dumps(text)  # not a JSON doc, just proving it is plain text
