"""Disconnect-proof progress journal.

Two machine stores, both under ``artifacts/progress`` (Google Drive on Colab):

* ``state.json`` - latest known state, rewritten atomically after every update.
* ``runs.jsonl`` - append-only event log (never rewritten or truncated).

Plus a human-readable ``progress.md`` written to **the repo root AND artifacts**
so it survives both a lost VM and a fresh git clone. Only the block between the
``BEGIN:AUTO`` / ``END:AUTO`` markers is machine-written; hand-written notes
outside that block survive every update.

Pure stdlib on purpose: this must work on a fresh Colab VM *before* any ML
dependency is installed (i.e. immediately after a disconnect).
"""

from __future__ import annotations

import json
import os
import platform
import time
from pathlib import Path
from typing import Any

from .paths import DEFAULT_RUN, Paths

BEGIN = "<!-- BEGIN:AUTO (generated by sheng_chatterbox.progress, do not edit) -->"
END = "<!-- END:AUTO -->"

# Stage -> (human label, command that advances it)
STAGES: dict[str, tuple[str, str]] = {
    "setup": ("Environment (torch + chatterbox-tts) ready", "sheng-chatterbox env"),
    "data": ("Dataset downloaded, 16 kHz WAVs + manifests built", "sheng-chatterbox data"),
    "model": ("ResembleAI/chatterbox snapshot downloaded", "sheng-chatterbox model"),
    "train": ("T3 fine-tuning (Sheng)", "sheng-chatterbox train"),
    "eval": ("Checkpoint evaluation / A-B listening", "sheng-chatterbox eval"),
    "export": ("Package final T3 + samples", "sheng-chatterbox export"),
}

MD_HEADER = """# Progress - Chatterbox x Sheng (Swahili + English) T3 fine-tune

Base model: `ResembleAI/chatterbox` multilingual T3 (`t3_mtl23ls_v2.safetensors`,
Llama-520M backbone; `sw` = Swahili is already in `SUPPORTED_LANGUAGES`).
Dataset: `lyle-mlengineer/kenyan-celebs` (~42 clips x 30 s, single speaker "abel", Sheng).
Method: full fine-tune of **T3 only** (the T3 LM is 0.5B; the voice encoder, the
S3 tokenizer and the s3gen vocoder stay frozen).

**After a Colab disconnect, run this first (same order, same commands):**

```bash
%cd /content/audio-speech-ai/finetune-chatterbox   # wherever you cloned the repo
!pip install -q -e .
!sheng-chatterbox status                      # what is done + where checkpoints are
!sheng-chatterbox all --resume --max-hours 8  # skips finished stages, resumes training
```

"""

MD_NOTES = """
## Notes / decisions (hand-written, preserved by the updater)

- **Fine-tune T3 only.** Chatterbox = `ve` (speaker embedding) + `t3` (text tokens ->
  speech tokens, 0.5B Llama) + `s3gen` (token -> waveform). A new timbre/accent lives
  in T3; the other two are frozen so audio quality cannot regress.
- **Multilingual checkpoint, not the English one.** `ChatterboxMultilingualTTS`
  already lists Swahili (`sw`), so fine-tuning only has to learn *Sheng* (the
  Swahili/English code-switch + abel's voice), not Swahili from scratch.
- **16 kHz mono WAVs** are what both the voice encoder (`S3_SR`) and the S3 tokenizer
  consume; output audio stays 24 kHz (`S3GEN_SR`) because s3gen is untouched.
- **Checkpoints live on Drive**: `checkpoints/<run>/step_%07d/t3_cfg.safetensors`
  (+ `latest/`). The `` `latest` `` copy is what `train --resume` loads, so a
  disconnect costs at most `save_interval` steps (default 100).
- **Checkpoints are written in fp16** (~1 GB each instead of 2.1 GB) and only the
  last `keep_last` step dirs are kept, so the run fits in a free Drive quota.
  Optimizer state is not saved: resume restarts the LR schedule from the saved step.
- **A `--max-hours` guard** stops training gracefully just before the Colab session
  limit; the trainer's SIGINT handler writes a checkpoint first.
- **Overfitting is the main failure mode.** 21 min of audio, 600 steps. Listen at
  every saved step; the checkpoint that still follows *new* text is the good one.
- **Exaggeration 0.5** is what training uses (`emotion_adv` conditioning); keep the
  same value at inference or the voice shifts.
"""



def _now() -> str:
    return time.strftime("%Y-%m-%d %H:%M:%S")


def _atomic_write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with tmp.open("w", encoding="utf-8", newline="\n") as f:
        f.write(text)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)


def _replace_block(text: str, block: str) -> str:
    if BEGIN in text and END in text:
        head, _, rest = text.partition(BEGIN)
        _, _, tail = rest.partition(END)
        return head + block + tail
    if not text.strip():
        return MD_HEADER + block + MD_NOTES
    return text.rstrip() + "\n\n" + block + "\n" + MD_NOTES


class Progress:
    """Read/write the durable progress state."""

    def __init__(self, paths: Paths):
        self.paths = paths
        paths.progress_dir.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------ state
    def load(self) -> dict[str, Any]:
        try:
            with self.paths.state_json.open("r", encoding="utf-8") as f:
                data = json.load(f)
        except (FileNotFoundError, json.JSONDecodeError):
            data = {}
        data.setdefault("stages", {})
        data.setdefault("created", _now())
        return data

    def save(self, state: dict[str, Any]) -> None:
        state["updated"] = _now()
        state["host"] = {"platform": platform.platform(), "python": platform.python_version()}
        _atomic_write_text(self.paths.state_json, json.dumps(state, indent=2, ensure_ascii=False))

    def set_state(self, **kwargs: Any) -> dict[str, Any]:
        state = self.load()
        state.update(kwargs)
        self.save(state)
        return state

    # ----------------------------------------------------------- events
    def event(self, stage: str, status: str = "done", note: str = "", **extra: Any) -> None:
        """Record a stage transition and refresh progress.md."""
        if stage not in STAGES:
            raise KeyError(f"unknown stage {stage!r}; known: {sorted(STAGES)}")
        state = self.load()
        state["stages"][stage] = {"status": status, "note": note, "at": _now(), **extra}
        if status == "running":
            state["current_stage"] = stage
        elif state.get("current_stage") == stage:
            state["current_stage"] = None
        self.save(state)

        evt = {"ts": _now(), "stage": stage, "status": status, "note": note, **extra}
        self.paths.runs_jsonl.parent.mkdir(parents=True, exist_ok=True)
        with self.paths.runs_jsonl.open("a", encoding="utf-8") as f:
            f.write(json.dumps(evt, ensure_ascii=False) + "\n")

        self.write_markdown(state)

    def heartbeat(self, run: str, step: int | None, note: str = "", **extra: Any) -> None:
        """Cheap periodic update while long work runs (no runs.jsonl entry)."""
        state = self.load()
        state["run"] = run
        if step is not None:
            state["current_step"] = int(step)
        if note:
            state["heartbeat_note"] = note[:400]
        if extra:
            state.update(extra)
        self.save(state)
        self.write_markdown(state)

    def is_done(self, stage: str) -> bool:
        return self.load()["stages"].get(stage, {}).get("status") == "done"

    def next_step(self) -> str:
        """One-line hint for what to run after a fresh clone / disconnect."""
        return self._next_step(self.load())

    # -------------------------------------------------------- rendering
    def _next_step(self, state: dict[str, Any]) -> str:
        stages = state["stages"]
        for stage, (label, cmd) in STAGES.items():
            status = stages.get(stage, {}).get("status")
            if stage == "train" and status == "running":
                return f"`{cmd} --resume`   # training was interrupted - resume it"
            if stage == "train" and status == "partial":
                return f"`{cmd} --resume`   # partial training, continue"
            if status != "done":
                return f"`{cmd}`   # {label}"
        return "All stages done - `sheng-chatterbox status` to inspect, `sheng-chatterbox export` to package."

    def render_markdown(self, state: dict[str, Any] | None = None) -> str:
        state = state or self.load()
        stages = state["stages"]
        run = state.get("run", "run not set")
        lines = [BEGIN, "", f"_Last update: {state.get('updated', 'never')}  |  run: {run}_", ""]
        lines += ["| # | Stage | What it means | Status | When | Detail |", "|---|---|---|---|---|---|"]
        for i, (stage, (label, _cmd)) in enumerate(STAGES.items(), start=1):
            info = stages.get(stage, {})
            status = info.get("status", "todo")
            icon = {
                "done": "done",
                "running": "RUNNING",
                "partial": "partial",
                "failed": "FAILED",
            }.get(status, "todo")
            detail = str(info.get("note") or "").replace("|", "/").replace("\n", " ")
            lines.append(f"| {i} | `{stage}` | {label} | **{icon}** | {info.get('at', '-')} | {detail} |")
        lines.append("")

        if state.get("current_step") is not None:
            lines += [f"**Current step:** `{state['current_step']}`  ", ""]

        ckpt = state.get("checkpoint") or {}
        if ckpt:
            lines += [
                "### Last checkpoint",
                "",
                f"- step: `{ckpt.get('step')}`",
                f"- path: `{ckpt.get('path', '-')}`",
                f"- loss: `{ckpt.get('loss', '-')}`  (text `{ckpt.get('loss_text', '-')}` / speech `{ckpt.get('loss_speech', '-')}`)",
                "",
            ]
        if state.get("best_checkpoint"):
            lines += [f"**Best checkpoint (by eval):** `{state['best_checkpoint']}`", ""]
        if state.get("heartbeat_note"):
            lines += [f"_Last log line:_ `{state['heartbeat_note']}`", ""]

        lines += ["### Next command", "", f"> {self._next_step(state)}", ""]

        if state.get("notes"):
            lines += ["### Machine notes", ""]
            lines += [f"- {n}" for n in state["notes"]]

        lines += [
            "",
            "### Locations",
            "",
            f"- artifacts root: `{self.paths.artifacts}`",
            f"- pretrained checkpoint: `{self.paths.pretrained_dir}`",
            f"- base model files: `{self.paths.pretrained_dir}`",
            f"- manifests: `{self.paths.manifest_dir}`",
            f"- checkpoints: `{self.paths.checkpoint_dir(run)}`",
            f"- train log: `{self.paths.train_log(run)}`",
            f"- evals: `{self.paths.eval_dir(run)}`",
            "",
            END,
        ]
        return "\n".join(lines)

    def add_note(self, note: str) -> None:
        state = self.load()
        notes = state.setdefault("notes", [])
        notes.append(f"{_now()}: {note}")
        state["notes"] = notes[-40:]  # keep the journal small
        self.save(state)
        self.write_markdown(state)

    def write_markdown(self, state: dict[str, Any] | None = None) -> list[Path]:
        """Merge the AUTO block into every progress.md (repo + artifacts)."""
        block = self.render_markdown(state)
        written: list[Path] = []
        seen: set[Path] = set()
        for path in (self.paths.repo_progress_md, self.paths.artifacts_progress_md):
            path = path.resolve()
            if path in seen:
                continue
            seen.add(path)
            try:
                existing = path.read_text(encoding="utf-8") if path.exists() else self._default_md()
            except OSError:
                existing = self._default_md()
            _atomic_write_text(path, _replace_block(existing, block))
            written.append(path)
        return written

    def _default_md(self) -> str:
        return MD_HEADER + BEGIN + "\n" + END + "\n" + MD_NOTES

    # -------------------------------------------------------------- misc
    def tail_events(self, n: int = 15) -> list[dict[str, Any]]:
        try:
            lines = self.paths.runs_jsonl.read_text(encoding="utf-8").splitlines()
        except FileNotFoundError:
            return []
        out = []
        for line in lines[-n:]:
            try:
                out.append(json.loads(line))
            except json.JSONDecodeError:
                continue
        return out


def seed_progress_md(paths: Paths) -> Path:
    """Create progress.md from the template if it does not exist, then refresh."""
    p = Progress(paths)
    if not paths.state_json.exists():
        p.set_state(stages={}, run=DEFAULT_RUN)  # stamps `updated` so the journal is not "never"
    if not paths.repo_progress_md.exists():
        _atomic_write_text(paths.repo_progress_md, p._default_md())
    p.write_markdown()
    return paths.repo_progress_md
